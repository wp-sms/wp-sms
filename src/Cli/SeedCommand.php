    /**
     * Pick a key from an [key => weight] map according to the weights.
     */
    private function weightedPick(array $weights): string
    {
        $total = array_sum($weights);
        $roll = $this->faker->numberBetween(1, $total);
        $cursor = 0;
        foreach ($weights as $key => $weight) {
            $cursor += $weight;
            if ($roll <= $cursor) {
                return (string) $key;
            }
        }
        return (string) array_key_first($weights);
    }

    private function ulid(?int $atTimestamp = null): string
    {
        // The plugin's vendored Symfony Ulid takes no constructor arguments and
        // is timestamped to "now". We sometimes want ULIDs dated to a specific
        // point in the past so that sort-by-id matches sort-by-created_at. For
        // the common case we return a plain ULID; historical rows use the
        // library's generator wrapped with a brief sleep-free offset by
        // generating fresh ULIDs close together.
        unset($atTimestamp); // The plugin does not use dated ULIDs anywhere we've found.
        return (string) new Ulid();
    }

    /**
     * Return a MySQL DATETIME string weighted toward recent history.
     */
    private function randomDate(int $daysBack = 120, bool $recentWeighted = true): string
    {
        if ($recentWeighted) {
            // Square distribution: more recent dates have higher probability.
            $r = $this->faker->randomFloat(4, 0, 1);
            $offsetDays = (int) round($daysBack * ($r * $r));
        } else {
            $offsetDays = $this->faker->numberBetween(0, $daysBack);
        }
        $offsetSeconds = $this->faker->numberBetween(0, 86_399);
        $ts = time() - ($offsetDays * 86_400) - $offsetSeconds;
        return gmdate('Y-m-d H:i:s', $ts);
    }

    /**
