    /** Counter used to hand out deterministic fake user IDs in dry-run mode. */
    private int $dryRunUserCounter = 900000;

    private function createSeededUser(array $spec): int
    {
        if ($this->dryRun) {
            // Hand out plausible, non-colliding fake IDs so downstream seeders
            // (verifications, user factors, auth logs) have something to
            // reference without actually inserting any users.
            return ++$this->dryRunUserCounter;
        }
        $existing = get_user_by('login', $spec['login']);
        if ($existing) {
            // Tag it so --clear can remove it if it wasn't already.
            update_user_meta($existing->ID, self::SEED_META_KEY, self::SEED_META_VALUE);
            return (int) $existing->ID;
        }
        $userId = wp_insert_user([
            'user_login'   => $spec['login'],
            'user_email'   => $spec['email'],
            'user_pass'    => wp_generate_password(16, true, true),
            'display_name' => $spec['display_name'],
            'first_name'   => $spec['first_name'],
            'last_name'    => $spec['last_name'],
            'role'         => $spec['role'],
        ]);
        if (is_wp_error($userId)) {
            WP_CLI::error('wp_insert_user failed: ' . $userId->get_error_message());
        }
        update_user_meta($userId, self::SEED_META_KEY, self::SEED_META_VALUE);
        return (int) $userId;
    }

