    private function runLoadProfile(): void
    {
        $this->log(sprintf('Running load profile (count=%d)...', $this->loadCount));

        $before = microtime(true);

        // Bulk-insert contacts using $wpdb directly in batches to be fast.
        global $wpdb;
        $contactsTable = $wpdb->prefix . 'wsms_contacts';
        $logsTable = $wpdb->prefix . 'wsms_message_logs';

        $batchSize = 200;
        $loadContactIds = [];

        for ($i = 0; $i < $this->loadCount; $i += $batchSize) {
            $values = [];
            $placeholders = [];
            $thisBatch = min($batchSize, $this->loadCount - $i);
            for ($j = 0; $j < $thisBatch; $j++) {
                $idx = $i + $j;
                $id = $this->ulid();
                $loadContactIds[] = $id;
                $email = 'load.' . $idx . '@load-test.wsms-demo.test';
                $phone = '+1415' . str_pad((string) (7000000 + $idx), 7, '0', STR_PAD_LEFT);
                $firstName = $this->faker->firstName();
                $lastName = $this->faker->lastName();
                $status = $this->weightedPick(['subscribed' => 90, 'bounced' => 8, 'complained' => 2]);
                $createdAt = $this->randomDate(120);
                $placeholders[] = '(%s, %s, %s, %s, %s, NULL, %s, %d, %d, NULL, NULL, %s, NULL, %s, %s)';
                array_push(
                    $values,
                    $id, $email, $phone, $firstName, $lastName, $status,
                    0, 0, 'import', $createdAt, $createdAt
                );
            }
            if ($this->dryRun) {
                continue;
            }
