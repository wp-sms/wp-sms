                    ]] : [],
                ];
            case 'mena_sms':
                $menaId = $this->tagIds['mena'] ?? null;
                return [
                    'exclude_unsubscribed' => true,
                    'sources' => $menaId ? [[
                        'type' => 'tags',
                        'tag_ids' => [$menaId],
                    ]] : [],
                ];
            case 'manual_list':
                return [
                    'exclude_unsubscribed' => true,
