            case 'vip_tag':
                $vipTagId = $this->tagIds['vip'] ?? null;
                return [
                    'exclude_unsubscribed' => true,
                    'sources' => $vipTagId ? [[
                        'type' => 'tags',
                        'tag_ids' => [$vipTagId],
                    ]] : [],
                ];
            case 'cart_abandoners':
                $tagId = $this->tagIds['cart-abandoner'] ?? null;
                return [
                    'exclude_unsubscribed' => true,
                    'sources' => $tagId ? [[
                        'type' => 'tags',
