        'wsms_tags',
        'wsms_contacts',
        'wsms_auth_logs',
        'wsms_user_factors',
        'wsms_verifications',
    ];

    /** Tables whose seeded rows are linked by user_id (deleted as a safety net alongside manifest IDs). */
    private const USER_LINKED_TABLES = [
        'wsms_auth_logs',
        'wsms_user_factors',
        'wsms_verifications',
    ];

    private Faker $faker;
    private bool $dryRun = false;
    private bool $force = false;
    private bool $yes = false;
    private int $loadCount = 5000;

    /** IDs of all seeded rows, keyed by table suffix. Persisted as manifest for targeted cleanup. */
    private array $manifest = [];

    /** Cached lookups populated during seeding, consumed by later steps. */
    private array $userIds = [];      // [handle => user_id]
    private array $tagIds = [];       // [slug => ulid]
    private array $contactIds = [];   // [index => ulid]
    private array $listIds = [];      // [slug => ulid]
    private array $campaignIds = [];  // [slug => ulid]
    private array $flowIds = [];      // [slug => ulid]
    private array $flowExecutionIds = []; // [index => ulid]

    /**
     * Seeds the WSMS database with realistic, marketing-grade test data.
     *
     * ## OPTIONS
     *
     * [--profile=<profile>]
     * : Which data profile to load. demo = small rich realistic dataset.
     * scenarios = edge-case rows on top of demo. load = bulk contacts and
     * message_logs for pagination/search stress. all = demo + scenarios + load.
     * ---
     * options:
     *   - demo
     *   - scenarios
     *   - load
     *   - all
     * ---
     *
     * [--count=<n>]
     * : Override the number of bulk rows generated by the "load" profile.
     * ---
     * default: 5000
     * ---
     *
     * [--clear]
     * : Remove seeder-inserted data using the stored manifest (non-seeded rows
     * are preserved). Falls back to full table truncation if no manifest exists.
     * Passed without --profile, the command wipes and exits.
     *
     * [--dry-run]
     * : Print what would be inserted without touching the database.
     *
     * [--force]
     * : Append to an already-seeded database instead of refusing.
     *
     * [--yes]
     * : Skip confirmation prompts (for --clear).
     *
     * [--i-know-this-is-production]
     * : Required alongside --yes when running on a production environment.
     *
     * ## EXAMPLES
     *
     *     wp wsms seed
     *     wp wsms seed --clear --yes
     *     wp wsms seed --profile=scenarios --force
     *     wp wsms seed --profile=load --count=20000 --force
     *     wp wsms seed --profile=demo --dry-run
     *
     * @when after_wp_load
     */
    public function __invoke(array $args, array $assoc_args): void
    {
        $this->bootstrap($assoc_args);

        $profile = $assoc_args['profile'] ?? 'demo';
        $clearRequested = isset($assoc_args['clear']);

        if ($clearRequested) {
            $this->clearSeededData();
            if (! isset($assoc_args['profile'])) {
                return;
            }
        }

        $this->guardIdempotency();

        switch ($profile) {
            case 'demo':
                $this->runDemoProfile();
                break;
            case 'scenarios':
                $this->runScenariosProfile();
                break;
            case 'load':
                $this->runLoadProfile();
                break;
            case 'all':
                $this->runDemoProfile();
                $this->runScenariosProfile();
                $this->runLoadProfile();
                break;
            default:
                WP_CLI::error(sprintf('Unknown profile: %s', $profile));
        }

        $this->writeSentinel($profile);

        WP_CLI::success(sprintf(
            'Seed complete (profile=%s%s).',
            $profile,
            $this->dryRun ? ', DRY RUN' : ''
        ));
    }

    // ─────────────────────────────────────────────────────────────
    // Bootstrap & safety
    // ─────────────────────────────────────────────────────────────

    private function bootstrap(array $assoc_args): void
    {
        $this->dryRun = isset($assoc_args['dry-run']);
        $this->force = isset($assoc_args['force']);
        $this->yes = isset($assoc_args['yes']);
        $this->loadCount = (int) ($assoc_args['count'] ?? 5000);

        $this->guardProduction($assoc_args);
        $this->guardFakerAvailable();
        $this->guardTablesExist();

        $this->faker = FakerFactory::create();
        $this->faker->seed(20260408);

        $this->log(sprintf(
            'WSMS seeder bootstrapped (dry-run=%s, force=%s).',
            $this->dryRun ? 'yes' : 'no',
            $this->force ? 'yes' : 'no'
        ));
    }

    private function guardProduction(array $assoc_args): void
    {
        if (! $this->looksLikeProduction()) {
            return;
        }
        if (! isset($assoc_args['yes']) || ! isset($assoc_args['i-know-this-is-production'])) {
            WP_CLI::error(
                'Refusing to seed on a production environment. '
                . 'If this is actually a local site, set WP_ENVIRONMENT_TYPE '
                . "to 'local' in wp-config.php, or pass "
                . '--yes --i-know-this-is-production.'
            );
        }
        WP_CLI::warning('Seeding a PRODUCTION environment because you insisted.');
    }

    /**
     * We treat a site as production ONLY if wp_get_environment_type() says so
     * AND the site URL does not look obviously local. This saves users from
     * needing to set WP_ENVIRONMENT_TYPE on every dev box while still being
     * paranoid on real hosts.
     */
    private function looksLikeProduction(): bool
    {
        if (! function_exists('wp_get_environment_type')) {
            return false;
        }
        if (wp_get_environment_type() !== 'production') {
            return false;
        }
        $host = (string) parse_url((string) get_site_url(), PHP_URL_HOST);
        $localHosts = ['localhost', '127.0.0.1', '::1'];
        if (in_array($host, $localHosts, true)) {
            return false;
        }
        $localSuffixes = ['.test', '.local', '.localhost', '.example', '.lndo.site'];
        foreach ($localSuffixes as $suffix) {
            if (str_ends_with($host, $suffix)) {
                return false;
            }
        }
        return true;
    }

    private function guardFakerAvailable(): void
    {
        if (class_exists(FakerFactory::class)) {
            return;
        }
        // The plugin's runtime autoloader (packages/autoload.php) only maps
        // scoped deps. Faker is a dev-only package in vendor/; load it
        // directly when we're running inside the CLI seeder.
        $vendorAutoload = dirname(__DIR__, 2) . '/vendor/autoload.php';
        if (file_exists($vendorAutoload)) {
            require_once $vendorAutoload;
        }
        if (! class_exists(FakerFactory::class)) {
            WP_CLI::error(
                'Faker is not available. Run `composer install` inside '
                . 'wp-content/plugins/wp-sms to install dev dependencies.'
            );
        }
    }

    private function guardTablesExist(): void
    {
        global $wpdb;
        $missing = [];
        foreach (self::TABLES_REVERSE_TOPO as $suffix) {
            $table = $wpdb->prefix . $suffix;
            $exists = $wpdb->get_var($wpdb->prepare('SHOW TABLES LIKE %s', $table));
            if ($exists !== $table) {
                $missing[] = $suffix;
            }
        }
        if ($missing) {
            WP_CLI::error(sprintf(
                'Missing WSMS tables: %s. Deactivate and reactivate the plugin to run migrations.',
                implode(', ', $missing)
            ));
        }
    }

    private function guardIdempotency(): void
    {
        if ($this->force || $this->dryRun) {
            return;
        }
        $existing = get_option(self::SENTINEL_OPTION, '');
        if ($existing !== '') {
            WP_CLI::error(sprintf(
                'Already seeded (run_id=%s). Use --clear to wipe and reseed, or --force to append.',
                $existing
            ));
        }
    }

    private function writeSentinel(string $profile): void
    {
        if ($this->dryRun) {
            return;
        }
        $runId = sprintf('%s-%s', $profile, gmdate('Ymd-His'));
        update_option(self::SENTINEL_OPTION, $runId, false);
        $this->persistManifest();
        $this->log(sprintf('Sentinel written: %s', $runId));
    }

    private function persistManifest(): void
    {
        if ($this->dryRun) {
            return;
        }
        update_option(self::MANIFEST_OPTION, wp_json_encode($this->manifest), false);
    }

    // ─────────────────────────────────────────────────────────────
    // Clear
    // ─────────────────────────────────────────────────────────────

    private function clearSeededData(): void
    {
        global $wpdb;

        $raw = get_option(self::MANIFEST_OPTION, '');
        $manifest = $raw ? json_decode($raw, true) : null;

        if (! is_array($manifest)) {
            $this->clearSeededDataLegacy();
            return;
        }

        if (! $this->yes && ! $this->dryRun) {
            WP_CLI::confirm('About to delete seeder-inserted data (non-seeded rows are preserved). Continue?');
        }

        $this->log('Clearing seeded data (targeted)...');

        $contactIds = $manifest['wsms_contacts'] ?? [];
        $seededUserIds = $wpdb->get_col($wpdb->prepare(
            "SELECT user_id FROM {$wpdb->usermeta} WHERE meta_key = %s AND meta_value = %s",
            self::SEED_META_KEY,
            self::SEED_META_VALUE
        ));

        foreach (self::TABLES_REVERSE_TOPO as $suffix) {
            $ids = $manifest[$suffix] ?? [];
            if ($suffix === 'wsms_contact_tag') {
                $this->log(sprintf('  - %s: via %d contact IDs', $suffix, count($contactIds)));
            } elseif (in_array($suffix, self::USER_LINKED_TABLES, true)) {
                $this->log(sprintf('  - %s: %d IDs + by %d user IDs', $suffix, count($ids), count($seededUserIds)));
            } else {
                $this->log(sprintf('  - %s: %d IDs', $suffix, count($ids)));
            }
        }
        $this->log(sprintf('  - wp_users: %d', count($seededUserIds)));

        if ($this->dryRun) {
            $this->log('Dry run: no rows deleted.');
            return;
        }

        $totalDeleted = 0;
        foreach (self::TABLES_REVERSE_TOPO as $suffix) {
            $table = $wpdb->prefix . $suffix;

            if ($suffix === 'wsms_contact_tag') {
                if ($contactIds) {
                    $totalDeleted += $this->deleteInBatches($table, 'contact_id', $contactIds);
                }
                continue;
            }

            $ids = $manifest[$suffix] ?? [];
            if ($ids) {
                $totalDeleted += $this->deleteInBatches($table, 'id', $ids);
            }

            if (in_array($suffix, self::USER_LINKED_TABLES, true) && $seededUserIds) {
                $totalDeleted += $this->deleteInBatches($table, 'user_id', $seededUserIds);
            }
        }

        if (! function_exists('wp_delete_user')) {
            require_once ABSPATH . 'wp-admin/includes/user.php';
        }
        foreach ($seededUserIds as $uid) {
            wp_delete_user((int) $uid);
        }

        delete_option(self::MANIFEST_OPTION);
        delete_option(self::SENTINEL_OPTION);

        WP_CLI::success(sprintf(
            'Cleared %d seeded rows and %d WP users.',
            $totalDeleted,
            count($seededUserIds)
        ));
    }

    /**
     * Fallback for databases seeded before manifest tracking was added.
     */
    private function clearSeededDataLegacy(): void
    {
        global $wpdb;

        WP_CLI::warning('No seed manifest found — falling back to full table truncation.');

        if (! $this->yes && ! $this->dryRun) {
            WP_CLI::confirm('About to TRUNCATE all WSMS tables and delete seeded WP users. Continue?');
        }

        $this->log('Clearing all data (legacy)...');

        $totals = [];
        foreach (self::TABLES_REVERSE_TOPO as $suffix) {
            $table = $wpdb->prefix . $suffix;
            $count = (int) $wpdb->get_var("SELECT COUNT(*) FROM {$table}");
            $totals[$suffix] = $count;
        }
        $seededUserIds = $wpdb->get_col($wpdb->prepare(
            "SELECT user_id FROM {$wpdb->usermeta} WHERE meta_key = %s AND meta_value = %s",
            self::SEED_META_KEY,
            self::SEED_META_VALUE
        ));

        foreach ($totals as $suffix => $count) {
            $this->log(sprintf('  - %s: %d rows', $suffix, $count));
        }
        $this->log(sprintf('  - wp_users (seeded): %d', count($seededUserIds)));

        if ($this->dryRun) {
            $this->log('Dry run: no rows deleted.');
            return;
        }

        foreach (self::TABLES_REVERSE_TOPO as $suffix) {
            $table = $wpdb->prefix . $suffix;
            $wpdb->query("TRUNCATE TABLE {$table}");
        }

        if (! function_exists('wp_delete_user')) {
            require_once ABSPATH . 'wp-admin/includes/user.php';
        }
        foreach ($seededUserIds as $uid) {
            wp_delete_user((int) $uid);
        }

        delete_option(self::MANIFEST_OPTION);
        delete_option(self::SENTINEL_OPTION);

        WP_CLI::success(sprintf(
            'Cleared %d WSMS rows and %d seeded users (legacy truncate).',
            array_sum($totals),
            count($seededUserIds)
        ));
    }

